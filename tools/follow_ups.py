"""Gather everything that needs a follow-up action into one markdown report, for the weekly Follow-ups issue.

Reads data/ only: open register items, readiness gates not yet passed, requirements waiting or planned, sources past
or near their re-check date, dates coming up, and data files due a review. It reports; it never edits, merges or
publishes. Run: python3 -I tools/follow_ups.py [--today YYYY-MM-DD]
"""
import argparse, datetime, json, os

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(n):
    return json.load(open(os.path.join(R, "data", n), encoding="utf-8"))


def report(today):
    d = lambda s: datetime.date.fromisoformat(s)
    reg, rd, pd, src, lat = load("registers.json"), load("readiness.json"), load("product.json"), load("youth-sources.json"), load("latest.json")
    out = [f"## Follow-ups due, {today}", "", "Generated by `tools/follow_ups.py` from `data/`. Tick an item here when it is done, then change the data file in a pull request: this issue is rewritten each Monday.", ""]
    gates = [g for g in rd["gates"] if g["status"] != "Pass"]
    out += ["### Readiness gates not yet passed", ""] + [f"- [ ] **{g['id']}** ({g['moscow']}, {g['status']}) {g['item']}. Who: {g['who'] or 'not named'}" for g in sorted(gates, key=lambda g: ("Must", "Should", "Could").index(g["moscow"]) if g["moscow"] in ("Must", "Should", "Could") else 9)] + [""]
    out += ["### Open items", ""] + [f"- [ ] **{o['id']}** {o['what']} Who: {o['who']}" for o in reg["open"]] + [""]
    req = [b for b in pd["backlog"] if b["status"] != "Done"]
    out += ["### Requirements not done", ""] + [f"- [ ] **{b['id']}** ({b['moscow']}, {b['status']}) {b['title']}" for b in req] + [""]
    due = []
    for s in src["sources"]:
        left = (d(s["checked"]) + datetime.timedelta(days=s.get("review_days", 90)) - today).days
        if left <= 14: due.append((left, s))
    due.sort(key=lambda x: x[0])
    out += ["### Sources to re-check (overdue or due within 14 days)", ""] + [f"- [ ] {s['name']} ({s['provenance']}, checked {s['checked']}, {'overdue by ' + str(-l) + ' days' if l < 0 else 'due in ' + str(l) + ' days'})" for l, s in due] + ([""] if due else ["None.", ""])
    soon = [i for i in lat["items"] if 0 <= (d(i["date"]) - today).days <= 21]
    out += ["### Dates in the next three weeks", ""] + [f"- [ ] {i['date']}: {i['title']}" for i in soon] + ([""] if soon else ["None.", ""])
    stale = []
    for n in sorted(os.listdir(os.path.join(R, "data"))):
        x = load(n)
        if isinstance(x, dict) and "checked" in x and "review_days" in x:
            left = (d(x["checked"]) + datetime.timedelta(days=x["review_days"]) - today).days
            if left <= 14: stale.append(f"- [ ] `data/{n}` review {'overdue by ' + str(-left) + ' days' if left < 0 else 'due in ' + str(left) + ' days'}")
    out += ["### Data files due a review", ""] + (stale or ["None."]) + [""]
    out += ["### Every release", "", "- [ ] New terms added to `data/glossary.json` (glossary, thesaurus, graph and tooltips; check_site S16 enforces it)",
            "- [ ] `data/changelog.json` and `data/product.json` updated for what changed", ""]
    n = len(gates) + len(reg["open"]) + len(req) + len(due) + len(soon) + len(stale)
    return n, "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--today", default=datetime.date.today().isoformat())
    n, md = report(datetime.date.fromisoformat(ap.parse_args().today))
    print(md)
